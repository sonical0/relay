#!/usr/bin/env node
// Supervision guard: PreToolUse hook (matcher Bash) that refuses a `git push` against the protocol rules.
// Installed globally by relay-setup-hook.js; it exits at once for any command without "push" or npm/yarn.
//
// The push rules used to live in the skill's prose; here they are enforced, not just reminded:
//   - never forced (--force, --force-with-lease, --mirror, --delete, +refspec) nor --all;
//   - only the integrator pushes to the base branch;
//   - a manager pushes only ITS branch, the one it declared (`sup.py manager X --branch ...`).
// Outside a supervision (pane absent from the index), or at the slightest doubt (unreadable file, no git): let it
// through, and likewise when the project's board no longer answers (stale registration, board-alive.js). A guard
// that blocks wrongly costs more than it protects. Exit 2 + message on stderr = refusal (Claude Code).
//
// Data: `.relay-supervision/index.json` (pane -> "<project>/<X>.md") and `<project>.guard.json` (base branch,
// integrator, branch and role of each manager), generated by reprise.py on every board change.
// Variable: SUP_RELAY_STATE (same directory as reprise.py; tests).
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const { boardAlive } = require('./board-alive.js');

const FORCE = /^(-f|--force|--force-with-lease(=.*)?|--force-if-includes|--mirror|--delete|-d|--all|--prune)$/;

/** The `git push` calls of a command line: [{ args: [...] }], one entry per command (&&, ||, ;, |, newline). */
function pushes(command) {
  const out = [];
  for (const seg of String(command).split(/&&|\|\||;|\||\r?\n/)) {
    const m = seg.match(/(?:^|\s)git((?:\s+-[A-Za-z]\s+\S+|\s+--[\w-]+(?:=\S+)?)*)\s+push(?:\s+(.*))?$/);
    if (m) out.push({ args: (m[2] || '').trim().split(/\s+/).filter(Boolean).map(a => a.replace(/^["']|["']$/g, '')) });
  }
  return out;
}

/** Destination branch of a refspec (`HEAD:dev`, `feat/x`, `HEAD`, `refs/heads/x`); `current`: current branch. */
function destination(refspec, current) {
  let dst = refspec.includes(':') ? refspec.split(':').pop() : refspec;
  if (dst === 'HEAD' || dst === '') dst = current;
  return dst.replace(/^refs\/heads\//, '');
}

/** Refusal reason readable from the command alone (forced, deleting or global push), or null. */
function forbidden(command) {
  for (const { args } of pushes(command)) {
    const flags = args.filter(a => a.startsWith('-') && a !== '-u' && a !== '--set-upstream' && a !== '--no-verify');
    const positional = args.filter(a => !a.startsWith('-'));
    if (flags.some(f => FORCE.test(f)) || positional.some(p => p.startsWith('+'))) {
      return 'forced, deleting or global push (--force, --delete, --all, +refspec): never under supervision';
    }
  }
  return null;
}

/**
 * Decision for a command: null (allowed) or the refusal reason.
 * who: { id, role, branch } of the manager; rules: { base }; current(): current branch (called if needed).
 */
function decide(command, who, rules, current) {
  const force = forbidden(command);
  if (force) return force;
  for (const { args } of pushes(command)) {
    const positional = args.filter(a => !a.startsWith('-'));
    const refspecs = positional.slice(1);  // the first argument is the remote
    const targets = (refspecs.length ? refspecs : ['HEAD']).map(r => destination(r, current()));
    for (const dst of targets) {
      if (!dst) return 'destination branch not found: give the refspec (git push origin <branch>)';
      if (dst === rules.base) {
        if (who.role !== 'integrator') return `only the integrator pushes to ${rules.base}: deliver your branch (sup.py submit) and leave it to the merge train`;
      } else if (who.id !== 'S' && dst !== who.branch) {
        return who.branch
          ? `Manager ${who.id} pushes only its declared branch (${who.branch}), not ${dst}`
          : `no branch declared for Manager ${who.id}: sup.py manager ${who.id} --branch ${dst}, then push again`;
      }
    }
  }
  return null;
}

// npm that rewrites node_modules: refused in a worktree whose node_modules is shared (junction).
const NPM_MUTATING = /(?:^|[\s;&|(])(?:npm|pnpm)(?:\.cmd)?(?:\s+-{1,2}[\w-]+(?:=\S+)?)*\s+(install|i|ci|add|uninstall|remove|rm|update|up|upgrade|dedupe|prune)(?=\s|$|[;&|)])|(?:^|[\s;&|(])yarn(?:\.cmd)?\s+(add|remove|install)(?=\s|$)/;

/** Does the command reinstall packages into a shared node_modules (link or junction)? -> reason, or null. */
function sharedNpm(command, cwd) {
  if (!NPM_MUTATING.test(command)) return null;
  try {
    if (fs.lstatSync(path.join(cwd, 'node_modules')).isSymbolicLink()) {  // an NTFS junction counts as a link
      return 'node_modules of this worktree is shared with the main checkout (shared_dirs): an npm install/ci ' +
        'here would rewrite it for every worker; adding a package goes through the integrator';
    }
  } catch { /* no node_modules */ }
  return null;
}

function stateDir() {
  return process.env.SUP_RELAY_STATE || process.env.SUP_REPRISE_DIR || path.join(process.env.RELAY_ROOT ? path.resolve(process.env.RELAY_ROOT) : path.join(__dirname, '..', '..'), '.relay-supervision');
}

function main() {
  let raw = '';
  try { raw = fs.readFileSync(0, 'utf8'); } catch { return 0; }
  let input;
  try { input = JSON.parse(raw); } catch { return 0; }
  const command = input?.tool_input?.command;
  // Nearly every command exits here, without reading any file.
  if (typeof command !== 'string' || !(command.includes('push') || /npm|yarn/.test(command))) return 0;
  const calls = pushes(command);
  const npm = NPM_MUTATING.test(command);
  if (!calls.length && !npm) return 0;
  const surface = process.env.WMUX_SURFACE_ID;
  const agent = process.env.SUP_AGENT;  // without wmux: <project>/<X>
  if (!surface && !agent) return 0;
  try {
    const dir = stateDir();
    let index = {};
    try { index = JSON.parse(fs.readFileSync(path.join(dir, 'index.json'), 'utf8')); } catch { /* unreadable index */ }
    const entry = (surface && index[surface]) || (/^[\w-]+\/[A-Za-z0-9]+$/.test(agent || '') ? `${agent}.md` : null);
    if (!entry) return 0;  // not a supervision agent
    const [project, file] = entry.split('/');
    const id = file.replace(/\.md$/, '');
    let rules = null;
    try { rules = JSON.parse(fs.readFileSync(path.join(dir, `${project}.guard.json`), 'utf8')); } catch { /* unreadable rules */ }
    if (!rules) {
      // Supervised pane but unreadable rules: the branch cannot be decided, but a forced push can still be refused,
      // since it reads from the command alone. Everything else passes (a broken guard must not block all work).
      const why = forbidden(command);
      if (why) {
        process.stderr.write(`Supervision (${project}): git push refused — ${why}.\n`);
        return 2;
      }
      return 0;
    }
    // Session from another launch (SUP_RUN token set by start-manager.ps1): not part of this supervision.
    // No token (older manager) or rules without a token (older server): previous behaviour.
    if (rules.run && process.env.SUP_RUN && process.env.SUP_RUN !== rules.run) return 0;
    // Board stopped: the supervision is over, the registration is stale. Let it through, as outside a supervision.
    if (boardAlive(rules) === false) return 0;
    if (npm) {
      const why = sharedNpm(command, input.cwd || process.cwd());
      if (why) {
        process.stderr.write(`Supervision (${project}): command refused — ${why}.\n`);
        return 2;
      }
      if (!calls.length) return 0;
    }
    const m = rules.managers?.[id] || {};
    const who = { id, role: m.role || '', branch: m.branch || '' };
    const current = () => {
      try {
        return execFileSync('git', ['rev-parse', '--abbrev-ref', 'HEAD'], { cwd: input.cwd || process.cwd(), encoding: 'utf8', timeout: 3000 }).trim();
      } catch { return ''; }
    };
    const why = decide(command, who, rules, current);
    if (why) {
      process.stderr.write(`Supervision (${project}): git push refused — ${why}.\n`);
      return 2;
    }
  } catch { return 0; }
  return 0;
}

if (require.main === module) process.exit(main());
module.exports = { pushes, destination, decide, forbidden, sharedNpm, NPM_MUTATING };
